from __future__ import annotations

import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

from quasar.core.engine import run_assessment
from quasar.core.process_runner import ProcessResult
from quasar.modules.registry import TOOL_SPECS


class MockedWorkflowTests(unittest.TestCase):
    def test_full_workflow_merges_scoped_candidates_and_writes_alive_urls(self):
        setup_rows = []
        for spec in TOOL_SPECS:
            setup_rows.append({
                "tool": spec.display_name,
                "status": "available",
                "path": f"/fake/bin/{spec.key}",
                "version_or_probe": "mock version",
            })
        setup_report = {
            "timestamp_utc": "2026-01-01T00:00:00+00:00",
            "platform": "test",
            "python": "test",
            "auto_install_enabled": False,
            "tools": setup_rows,
            "extra_prerequisites": [],
            "all_tools_verified": True,
            "unavailable_tools": [],
            "strict_mode_blocked": False,
        }

        def fake_run_process(command, timeout=300, cwd=None):
            command = [str(item) for item in command]
            cmd_name = Path(command[0]).name
            stdout = "api.example.com\nnotexample.com\n"
            stderr = ""
            returncode = 0

            # Mimic native output files generated by tools. The engine should read these
            # in addition to stdout and then apply exact target scope validation.
            if "-o" in command:
                idx = command.index("-o") + 1
                out_path = Path(command[idx])
                if cmd_name == "sublist3r":
                    out_path.parent.mkdir(parents=True, exist_ok=True)
                    out_path.write_text("www.example.com\nnotexample.com\n", encoding="utf-8")
                elif cmd_name == "amass":
                    out_path.parent.mkdir(parents=True, exist_ok=True)
                    out_path.write_text("mail.example.com\n", encoding="utf-8")
                elif cmd_name == "dnsrecon":
                    out_path.parent.mkdir(parents=True, exist_ok=True)
                    out_path.write_text("static.example.com\n", encoding="utf-8")
                elif cmd_name == "bbot":
                    out_path.mkdir(parents=True, exist_ok=True)
                    (out_path / "subdomains.txt").write_text("cdn.example.com\n", encoding="utf-8")
            if "-u" in command:
                out_path = Path(command[command.index("-u") + 1])
                out_path.parent.mkdir(parents=True, exist_ok=True)
                out_path.write_text("app.example.com\n", encoding="utf-8")
            if "--subfile" in command:
                out_path = Path(command[command.index("--subfile") + 1])
                out_path.parent.mkdir(parents=True, exist_ok=True)
                out_path.write_text("mail.example.com\n", encoding="utf-8")
            if "-f" in command and cmd_name == "theHarvester":
                prefix = Path(command[command.index("-f") + 1])
                prefix.parent.mkdir(parents=True, exist_ok=True)
                prefix.with_suffix(".html").write_text("dev.example.com", encoding="utf-8")
            if cmd_name == "puredns":
                if "--write" in command:
                    out_path = Path(command[command.index("--write") + 1])
                    out_path.parent.mkdir(parents=True, exist_ok=True)
                    out_path.write_text("dns.example.com\nnotexample.com\n", encoding="utf-8")
                stdout = "dns.example.com\nnotexample.com\n"
            if cmd_name == "httpx":
                stdout = ""
                out_path = Path(command[command.index("-o") + 1])
                out_path.parent.mkdir(parents=True, exist_ok=True)
                out_path.write_text("https://api.example.com [200]\nhttps://notexample.com [200]\n", encoding="utf-8")
            return ProcessResult(command, returncode, stdout, stderr, 0.01)

        with tempfile.TemporaryDirectory() as temp:
            args = SimpleNamespace(
                domain="Example.com.", list=None, output_dir=temp, no_install=True,
                strict_dependencies=False, include_apex=False,
            )
            with patch("quasar.core.engine.DependencyManager.ensure_all", return_value=setup_report), \
                 patch("quasar.core.engine.run_process", side_effect=fake_run_process):
                exit_code = run_assessment(args, {"tool_timeout": 5, "httpx_timeout": 1, "httpx_threads": 1, "httpx_retries": 0})

            self.assertEqual(exit_code, 0)
            run_dirs = [p for p in Path(temp).iterdir() if p.is_dir()]
            self.assertEqual(len(run_dirs), 1)
            target_dir = run_dirs[0] / "example.com"
            final_hosts = (target_dir / "Final_Subdomains.txt").read_text(encoding="utf-8").splitlines()
            self.assertIn("api.example.com", final_hosts)
            self.assertIn("www.example.com", final_hosts)
            self.assertIn("dns.example.com", final_hosts)
            self.assertIn("cdn.example.com", final_hosts)
            self.assertNotIn("notexample.com", final_hosts)
            self.assertEqual(final_hosts, sorted(set(final_hosts)))
            alive_urls = (target_dir / "Alive_Subdomains.txt").read_text(encoding="utf-8").splitlines()
            self.assertEqual(alive_urls, ["https://api.example.com"])
            report = (run_dirs[0] / "run_report.json").read_text(encoding="utf-8")
            self.assertIn('"responsive_url_count_across_targets": 1', report)
            target_report = (target_dir / "run_report.json").read_text(encoding="utf-8")
            self.assertIn('"original_input": "Example.com."', target_report)
            self.assertIn('"normalized_target": "example.com"', target_report)

    def test_multi_target_run_creates_scoped_aggregate_files(self):
        setup_rows = [{
            "tool": spec.display_name, "status": "available", "path": f"/fake/bin/{spec.key}",
            "version_or_probe": "mock version",
        } for spec in TOOL_SPECS]
        setup_report = {
            "timestamp_utc": "2026-01-01T00:00:00+00:00", "platform": "test", "python": "test",
            "auto_install_enabled": False, "tools": setup_rows, "extra_prerequisites": [],
            "all_tools_verified": True, "unavailable_tools": [], "strict_mode_blocked": False,
        }

        def fake_run_process(command, timeout=300, cwd=None):
            command = [str(item) for item in command]
            key = Path(command[0]).name
            target = Path(cwd).name if cwd else "example.com"
            stdout = f"api.{target}\nnot{target}\n"
            if key == "httpx":
                stdout = ""
                output = Path(command[command.index("-o") + 1])
                output.parent.mkdir(parents=True, exist_ok=True)
                output.write_text(f"https://api.{target} [200]\nhttps://not{target} [200]\n", encoding="utf-8")
            elif key == "puredns":
                output_file = Path(command[command.index("--write") + 1])
                input_file = Path(command[command.index("resolve") + 1])
                output_file.parent.mkdir(parents=True, exist_ok=True)
                output_file.write_text(input_file.read_text(encoding="utf-8"), encoding="utf-8")
            elif "-o" in command:
                output = Path(command[command.index("-o") + 1])
                if key == "bbot":
                    output.mkdir(parents=True, exist_ok=True)
                    (output / "subdomains.txt").write_text(f"cdn.{target}\n", encoding="utf-8")
                else:
                    output.parent.mkdir(parents=True, exist_ok=True)
                    output.write_text(f"www.{target}\n", encoding="utf-8")
            elif "-u" in command:
                output = Path(command[command.index("-u") + 1])
                output.parent.mkdir(parents=True, exist_ok=True)
                output.write_text(f"app.{target}\n", encoding="utf-8")
            elif "--subfile" in command:
                output = Path(command[command.index("--subfile") + 1])
                output.parent.mkdir(parents=True, exist_ok=True)
                output.write_text(f"mail.{target}\n", encoding="utf-8")
            elif "--xml" in command:
                output = Path(command[command.index("--xml") + 1])
                output.parent.mkdir(parents=True, exist_ok=True)
                output.write_text(f"static.{target}\n", encoding="utf-8")
            return ProcessResult(command, 0, stdout, "", 0.01)

        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            list_file = root / "domains.txt"
            list_file.write_text("example.com\nexample.org\n", encoding="utf-8")
            args = SimpleNamespace(
                domain=None, list=str(list_file), output_dir=str(root / "results"), no_install=True,
                strict_dependencies=False, include_apex=False,
            )
            with patch("quasar.core.engine.DependencyManager.ensure_all", return_value=setup_report), \
                 patch("quasar.core.engine.run_process", side_effect=fake_run_process):
                exit_code = run_assessment(args, {"tool_timeout": 5, "httpx_timeout": 1, "httpx_threads": 1, "httpx_retries": 0})

            self.assertEqual(exit_code, 0)
            assessment = next((root / "results").iterdir())
            combined_final = (assessment / "combined" / "Final_Subdomains.txt").read_text(encoding="utf-8").splitlines()
            combined_alive = (assessment / "combined" / "Alive_Subdomains.txt").read_text(encoding="utf-8").splitlines()
            self.assertIn("api.example.com", combined_final)
            self.assertIn("api.example.org", combined_final)
            self.assertNotIn("notexample.com", combined_final)
            self.assertNotIn("notexample.org", combined_final)
            self.assertEqual(combined_alive, ["https://api.example.com", "https://api.example.org"])


if __name__ == "__main__":
    unittest.main(verbosity=2)
